"""Production label. Selected when DJANGO_ENV=production.

Debug is fixed off. Secrets, hosts, and the database come from the environment.
"""

import os

from django.core.exceptions import ImproperlyConfigured

from .base import *  # noqa: F403
from .env import env_bool, env_list, require_env

ENVIRONMENT_LABEL = "production"
DEBUG = False

SECRET_KEY = require_env("DJANGO_SECRET_KEY")
if SECRET_KEY.startswith("django-insecure-") or len(SECRET_KEY) < 50 or len(set(SECRET_KEY)) < 5:
    raise ImproperlyConfigured(
        "DJANGO_SECRET_KEY is not strong enough for the production label."
    )

ALLOWED_HOSTS = env_list("DJANGO_ALLOWED_HOSTS")
if not ALLOWED_HOSTS or "*" in ALLOWED_HOSTS:
    raise ImproperlyConfigured(
        "DJANGO_ALLOWED_HOSTS must list explicit hosts for the production label."
    )

