_BY_KEY = {name.casefold(): name for name in CANONICAL_SET}
_BY_KEY.update(_ALIAS_TO_OFFICIAL)


def canonical_country_name(value):
    """Return the official English name when this spelling is a known country."""
    text = " ".join(str(value or "").split())
    if not text:
        return ""
    return _BY_KEY.get(text.casefold(), text)


