def resolved_country_names(value):
    """Official countries this label should become. Empty means it is not a country."""
    text = " ".join(str(value or "").split())
    if not text:
        return []
    key = text.casefold()
    if key in JUNK_LABEL_REPLACEMENTS:
        return list(JUNK_LABEL_REPLACEMENTS[key])
    official = _BY_KEY.get(key)
    if official:
        return [official]
    return [text]
